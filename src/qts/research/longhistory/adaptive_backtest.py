"""End-to-end research integration for causal regime-aware strategy routing.

Candidate returns are generated by the existing execution engine, including
explicit spread, slippage, commission, stops, and financing assumptions. The
router uses only returns realized before each decision bar. This is research
infrastructure; it does not connect to a broker or authorize live orders.
"""
from __future__ import annotations

from collections.abc import Mapping

import numpy as np
import pandas as pd

from qts.research.longhistory.adaptive_router import (
    AdaptiveRoutingConfig,
    classify_market_regime,
    route_by_regime,
)
from qts.research.longhistory.engine import CostModel, run_plan
from qts.research.longhistory.signals import MAX_FRACTION, Plan


def build_adaptive_plan(
    bars: pd.DataFrame,
    candidate_plans: Mapping[str, Plan],
    costs: CostModel,
    *,
    routing_config: AdaptiveRoutingConfig | None = None,
    trend_lookback: int = 20,
    trend_threshold: float = 0.30,
    range_threshold: float = 0.20,
    atr_lookback: int = 14,
    volatility_window: int = 60,
    high_volatility_ratio: float = 1.50,
    initial_equity: float = 10_000.0,
    cap: float = MAX_FRACTION,
) -> tuple[Plan, pd.DataFrame, pd.DataFrame]:
    """Build a routed Plan plus diagnostics and candidate net-return streams.

    Each candidate is simulated through the normal execution engine over the
    same complete history. The resulting per-bar equity returns are the
    router's learning signal. Candidate Plan targets use NaN for "no change";
    they are forward-filled to explicit states before routing. If a selected
    candidate requests exposure but has no valid size on that bar, the routed
    plan fails flat rather than guessing a size.
    """
    if not isinstance(bars.index, pd.DatetimeIndex):
        raise ValueError("bars must use a DatetimeIndex")
    if not candidate_plans:
        raise ValueError("at least one candidate plan is required")
    if not np.isfinite(initial_equity) or initial_equity <= 0.0:
        raise ValueError("initial_equity must be finite and positive")
    if not np.isfinite(cap) or not 0.0 <= cap <= MAX_FRACTION:
        raise ValueError(f"cap must be finite and in [0, {MAX_FRACTION}]")

    n = len(bars)
    if n < 2:
        raise ValueError("at least two bars are required")
    index = bars.index
    regimes = classify_market_regime(
        bars,
        trend_lookback=trend_lookback,
        trend_threshold=trend_threshold,
        range_threshold=range_threshold,
        atr_lookback=atr_lookback,
        volatility_window=volatility_window,
        high_volatility_ratio=high_volatility_ratio,
    )

    returns_by_candidate: dict[str, np.ndarray] = {}
    states_by_candidate: dict[str, np.ndarray] = {}
    sizes_by_candidate: dict[str, np.ndarray] = {}
    stops_by_candidate: dict[str, np.ndarray] = {}
    for name, candidate in candidate_plans.items():
        if not isinstance(name, str) or not name:
            raise ValueError("candidate names must be non-empty strings")
        if len(candidate.target) != n:
            raise ValueError(f"{name}: plan length does not match bars")
        run = run_plan(
            bars,
            candidate,
            0,
            n,
            costs,
            initial_equity=initial_equity,
            force_close_end=True,
            cap=cap,
        )
        returns_by_candidate[name] = run.returns
        # NaN in a signal Plan means no state change, not a missing trade.
        states_by_candidate[name] = (
            pd.Series(candidate.target, index=index, dtype=float).ffill().fillna(0.0).to_numpy()
        )
        sizes_by_candidate[name] = (
            pd.Series(candidate.size, index=index, dtype=float).ffill().to_numpy()
        )
        stops_by_candidate[name] = (
            pd.Series(candidate.stop_dist, index=index, dtype=float).ffill().to_numpy()
        )

    net_returns = pd.DataFrame(returns_by_candidate, index=index, dtype=float)
    targets = pd.DataFrame(states_by_candidate, index=index, dtype=float)
    routing = route_by_regime(regimes, net_returns, targets, routing_config)

    routed_target = np.zeros(n, dtype=float)
    routed_size = np.full(n, np.nan)
    routed_stop = np.full(n, np.nan)
    routed_rebalance = np.zeros(n, dtype=bool)
    for i, selected in enumerate(routing["selected_strategy"].to_numpy()):
        if selected is None or pd.isna(selected):
            continue
        candidate = candidate_plans[str(selected)]
        target = float(states_by_candidate[str(selected)][i])
        size = float(sizes_by_candidate[str(selected)][i])
        stop = float(stops_by_candidate[str(selected)][i])
        if target != 0.0 and (not np.isfinite(size) or size <= 0.0):
            continue
        routed_target[i] = target
        routed_size[i] = size
        routed_stop[i] = stop
        routed_rebalance[i] = bool(candidate.rebalance[i])

    plan = Plan(
        target=routed_target,
        size=routed_size,
        stop_dist=routed_stop,
        rebalance=routed_rebalance,
        family="adaptive_regime_router",
        params={
            "candidate_count": len(candidate_plans),
            "routing_lookback": (routing_config or AdaptiveRoutingConfig()).lookback,
            "min_observations": (routing_config or AdaptiveRoutingConfig()).min_observations,
            "cost_basis": costs.basis,
            "initial_equity": float(initial_equity),
            "position_cap": float(cap),
        },
    )
    return plan, routing, net_returns
